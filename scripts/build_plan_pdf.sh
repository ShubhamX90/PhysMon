#!/bin/bash
# Build the plan of record from its LaTeX source and regenerate its searchable text.
#
#   docs/proposals/PhysMon_Research_v2.tex  ->  PhysMon_Research_v2.pdf  ->  PhysMon_Research_v2.extracted.txt
#
# Uses the separate conda environment "texbuild" (tectonic + python + pypdf; created 2026-11-11 for this
# purpose only, so the project environment "physmon" is untouched). Create it once with:
#   conda create -n texbuild -c conda-forge --override-channels tectonic python=3.12 pypdf
# Tectonic downloads the LaTeX packages it needs on first use. CPU only; no scheduler involvement.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
ENV_BIN="${TEXBUILD_BIN:-$HOME/.conda/envs/texbuild/bin}"
SRC="$REPO/docs/proposals/PhysMon_Research_v2.tex"
PDF="$REPO/docs/proposals/PhysMon_Research_v2.pdf"
TXT="$REPO/docs/proposals/PhysMon_Research_v2.extracted.txt"

"$ENV_BIN/tectonic" -X compile "$SRC"
chmod 644 "$PDF"

"$ENV_BIN/python" - "$PDF" "$TXT" <<'PY'
import datetime
import sys

import pypdf

pdf_path, txt_path = sys.argv[1], sys.argv[2]
reader = pypdf.PdfReader(pdf_path)
header = (
    f"# Derived text extraction of docs/proposals/PhysMon_Research_v2.pdf "
    f"(pypdf {pypdf.__version__}, {datetime.date.today().isoformat()}).\n"
    "# Layout (tables, columns) is flattened. The LaTeX source PhysMon_Research_v2.tex is the source of truth;\n"
    "# this file exists for search and is regenerated by scripts/build_plan_pdf.sh.\n"
)
with open(txt_path, "w", encoding="utf-8") as out:
    out.write(header)
    for number, page in enumerate(reader.pages, start=1):
        out.write(f"\n\n######## PAGE {number} ########\n")
        out.write(page.extract_text() or "")
print(f"{len(reader.pages)} pages -> {txt_path}")
PY
